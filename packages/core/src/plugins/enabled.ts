/**
 * 「这个内置能力现在启用吗」。
 *
 * 注册表在**每次查表时**调用它，而不是在装配阶段把被禁用的项筛掉 —— 于是启停是立即生效的：
 * 不需要重新注册、不需要重启、也不需要给注册表补一套「可撤销注册」的机制。代价是查表时多一次
 * 谓词调用（成员表只有个位数，可以忽略）。
 *
 * **三张注册表用同一个形状，各自被注入**：编辑器扩展、附件渲染器在渲染进程，
 * 文档处理器在主进程。它们的 id 空间拼在一起才是完整的设置项，但每个进程只认自己那几个 ——
 * 主进程读到的存档里带着渲染进程的 id，它只是永远命中不了。
 *
 * 不传时注册表当作「全启用」：那正是加这个机制之前的行为，也是所有测试的默认。
 */
export type CapabilityEnabled = (id: string) => boolean;

/** 缺省谓词。注册表在没有注入时用它，省得每个查表点都判一次 `undefined`。 */
export const ALL_CAPABILITIES_ENABLED: CapabilityEnabled = () => true;
